/// The entry point a run on a Raccoon device starts the app from in views
/// mode: the one raccoon_runtime's `ViewsEntrypoint` writes, which Lumide's
/// own views runs use too, so both leave the same file and neither makes
/// the Flutter tool compile it anew. A binding that lays the app's root out
/// in every view the runner gives it, then the app's own `main`.
///
/// Kept the same as raccoon_runtime's by a test in Lumide's tanuki module,
/// since this package can't depend on it (it isn't published).
String raccoonViewsEntrySource(String mainImport) =>
    _source.replaceFirst(_appMain, mainImport);

const _appMain = '__APP_MAIN__';

const _source = r'''
// Generated by Raccoon: the app shown as a device, in every view it is given.
// Rewritten as needed; edits here are lost.

import 'dart:math' as math;

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';

import '__APP_MAIN__' as app;

void main(List<String> args) {
  _RaccoonBinding();
  final Function entry = app.main;
  if (entry is dynamic Function(List<String>)) {
    entry(args);
    return;
  }
  (entry as dynamic Function())();
}

class _RaccoonBinding extends WidgetsFlutterBinding {
  @override
  Widget wrapWithDefaultView(Widget rootWidget) =>
      _RaccoonViews(child: rootWidget);
}
class _RaccoonViews extends StatefulWidget {
  const _RaccoonViews({required this.child});

  final Widget child;

  @override
  State<_RaccoonViews> createState() => _RaccoonViewsState();
}

class _RaccoonViewsState extends State<_RaccoonViews>
    with WidgetsBindingObserver {
  static const _channel = BasicMessageChannel<Object?>(
    'raccoon/views',
    JSONMessageCodec(),
  );

  late List<int> _ids = _viewIds();

  // Views beside the first that the app can't be laid out in: a global key
  // it holds (an app-wide navigator key) is in the first view already.
  final _refused = <int>{};

  FlutterExceptionHandler? _appsHandler;
  var _guarding = false;

  static List<int> _viewIds() => [
    for (final view in WidgetsBinding.instance.platformDispatcher.views)
      view.viewId,
  ]..sort();

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
    _guard();
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _ids = const [];
    _guard();
    super.dispose();
  }

  @override
  void didChangeMetrics() {
    final ids = _viewIds();
    if (ids.length == _ids.length &&
        ids.indexed.every((entry) => entry.$2 == _ids[entry.$1])) {
      return;
    }
    setState(() {
      _ids = ids;
      _refused.retainAll(ids);
    });
    _guard();
  }

  // While the app is in more than one view, the errors a second instance of
  // its root raises go through here first.
  void _guard() {
    final several = _ids.length > 1;
    if (several == _guarding) return;
    _guarding = several;
    if (several) {
      _appsHandler = FlutterError.onError;
      FlutterError.onError = _onError;
      return;
    }
    if (FlutterError.onError == _onError) FlutterError.onError = _appsHandler;
    _appsHandler = null;
  }

  void _onError(FlutterErrorDetails details) {
    final text = details.exceptionAsString();
    // The framework asserts on a second element of the same type taking a
    // key; one of another type is a duplicate GlobalKey.
    final sharedKey =
        text.contains('GlobalKey') || text.contains('oldElement.widget');
    final extra = [
      for (final id in _ids.skip(1))
        if (!_refused.contains(id)) id,
    ];
    if (!sharedKey || extra.isEmpty) {
      _appsHandler?.call(details);
      return;
    }
    _refused.addAll(extra);
    debugPrint(
      'Raccoon: this app can\'t show in more than one view: a global key it '
      'holds (a navigator key) is in its first view already. Views $extra '
      'show it no more; close them to go back to one view.',
    );
    _channel.send({
      'refused': extra,
      'reason': 'globalKey',
      'error': text.split('\n').first,
    });
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) setState(() {});
    });
    WidgetsBinding.instance.scheduleFrame();
  }

  @override
  Widget build(BuildContext context) {
    final dispatcher = WidgetsBinding.instance.platformDispatcher;
    return ViewCollection(
      views: [
        for (final id in _ids)
          if (dispatcher.view(id: id) case final view?)
            View(
              key: ValueKey(id),
              view: view,
              child: switch (_refused.contains(id)) {
                true => const _RaccoonRefused(),
                false => _RaccoonDevice(child: widget.child),
              },
            ),
      ],
    );
  }
}

class _RaccoonRefused extends StatelessWidget {
  const _RaccoonRefused();

  @override
  Widget build(BuildContext context) => const Directionality(
    textDirection: TextDirection.ltr,
    child: ColoredBox(
      color: Color(0xFF202124),
      child: Center(
        child: Padding(
          padding: EdgeInsets.all(24),
          child: Text(
            'This app can\'t show in a second view: a global key it holds '
            'is in its first view. Close this view.',
            textAlign: TextAlign.center,
            style: TextStyle(color: Color(0xFFE8EAED), fontSize: 14),
          ),
        ),
      ),
    ),
  );
}

/// The device [child]'s view is shown as, from the client: its safe area,
/// as MediaQuery.padding, and its platform.
class _RaccoonDevice extends StatefulWidget {
  const _RaccoonDevice({required this.child});

  final Widget child;

  @override
  State<_RaccoonDevice> createState() => _RaccoonDeviceState();
}

class _RaccoonDeviceState extends State<_RaccoonDevice>
    with WidgetsBindingObserver {
  static const _channel = BasicMessageChannel<Object?>(
    'raccoon/device',
    JSONMessageCodec(),
  );

  static bool _overriding = false;
  static TargetPlatform? _appsOwn;

  int? _viewId;
  EdgeInsets? _padding;

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    final id = View.of(context).viewId;
    if (id == _viewId) return;
    _viewId = id;
    _ask();
  }

  @override
  void didChangeMetrics() => _ask();

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    super.dispose();
  }

  Future<void> _ask() async {
    final Object? reply;
    try {
      reply = await _channel.send({'view': _viewId});
    } catch (_) {
      return;
    }
    if (!mounted) return;
    // No answer (a client that has none, or no profile) is the host: what
    // was set before goes (raccoon#235).
    final named = switch (reply) {
      final Map map => map,
      _ => const {},
    };
    // The platform is one for the whole app: view 0's says it, or views
    // that differ would flip it, a reassemble each time (#201).
    if (_viewId == 0) _target(named['platform']);
    final padding = switch (named['padding']) {
      [final num top, final num right, final num bottom, final num left] =>
        EdgeInsets.fromLTRB(
          left.toDouble(),
          top.toDouble(),
          right.toDouble(),
          bottom.toDouble(),
        ),
      _ => null,
    };
    if (padding != _padding) setState(() => _padding = padding);
  }

  // What the client names, in place of what the app set itself, which is
  // put back once the client names none.
  static void _target(Object? platform) {
    final named = TargetPlatform.values
        .where((value) => value.name == platform)
        .firstOrNull;
    if (named == null && !_overriding) return;
    if (named != null && !_overriding) _appsOwn = debugDefaultTargetPlatformOverride;
    final wanted = named ?? _appsOwn;
    _overriding = named != null;
    if (wanted == debugDefaultTargetPlatformOverride) return;
    debugDefaultTargetPlatformOverride = wanted;
    WidgetsBinding.instance.reassembleApplication();
  }

  @override
  Widget build(BuildContext context) {
    final padding = _padding;
    if (padding == null) return widget.child;
    final data = MediaQuery.of(context);
    final insets = data.viewInsets;
    // As MediaQueryData.fromView has it: what the keyboard covers is no
    // longer padding.
    return MediaQuery(
      data: data.copyWith(
        viewPadding: padding,
        padding: EdgeInsets.fromLTRB(
          math.max(0, padding.left - insets.left),
          math.max(0, padding.top - insets.top),
          math.max(0, padding.right - insets.right),
          math.max(0, padding.bottom - insets.bottom),
        ),
      ),
      child: widget.child,
    );
  }
}
''';
